import type { PokemonTypeName, PokemonRarity } from '../types';

export interface PokemonMeta {
  id: number;
  name: string;
  types: PokemonTypeName[];
  bst: number;
  rarity: PokemonRarity;
}

export function computeRarityFromBST(bst: number): PokemonRarity {
  if (bst >= 580) return 'ultra_rare';
  if (bst >= 400) return 'rare';
  return 'common';
}

/**
 * Safely parse JSON types string with fallback to ['normal']
 */
export function safeParsePokemonTypes(typesJson: unknown): PokemonTypeName[] {
  if (typeof typesJson !== 'string') return ['normal'];
  try {
    const parsed = JSON.parse(typesJson);
    return Array.isArray(parsed) && parsed.length > 0
      ? (parsed as PokemonTypeName[])
      : ['normal'];
  } catch {
    return ['normal'];
  }
}

